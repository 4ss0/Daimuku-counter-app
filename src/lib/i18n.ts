const DICTS: Record<Lang, Dict> = { it, en, ja };
const LOCALES: Record<Lang, string> = { it: 'it-IT', en: 'en-GB', ja: 'ja-JP' };

export function detectLang(): Lang {
  const langs = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [];
  for (const l of langs) {
    const p = (l || '').slice(0, 2).toLowerCase();
    if (p === 'it' || p === 'ja' || p === 'en') return p;
  }
  return 'en';
}

/** The language in use (already resolved from "auto"). */
export const lang = writable<Lang>(detectLang());

export const locale = derived(lang, (l) => LOCALES[l]);

export type TFn = (key: Key, vars?: Record<string, string | number>) => string;

export const t = derived(lang, (l): TFn => {
  const d = DICTS[l];
  return (key, vars) => {
    let s: string = d[key] ?? it[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
});

/** Exported for tests: every language defines every key. */
export function missingKeys(): string[] {
  const out: string[] = [];
  for (const [name, d] of Object.entries(DICTS)) {
    for (const k of Object.keys(it)) if (!(k in d)) out.push(`${name}:${k}`);
  }
  return out;
}
